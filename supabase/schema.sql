create extension if not exists pgcrypto;

create table if not exists public.app_users (
  id uuid primary key default gen_random_uuid(),
  telegram_user_id bigint not null unique,
  telegram_chat_id bigint not null,
  username text,
  first_name text,
  language_code text,
  locale text not null default 'ru' check (locale in ('ru', 'en', 'ar', 'zh', 'vi', 'es', 'fr')),
  language_selected boolean not null default false,
  status text not null default 'ACTIVE' check (status in ('ACTIVE', 'BLOCKED')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.items (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references public.app_users(id) on delete cascade,
  name varchar(80) not null,
  category text,
  private_description text,
  verification_hint text,
  status text not null default 'ACTIVE'
    check (status in ('ACTIVE', 'LOST', 'MATCHED', 'FOUND', 'RECOVERED', 'ARCHIVED')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.tags (
  id uuid primary key default gen_random_uuid(),
  public_token varchar(32) not null unique,
  item_id uuid not null unique references public.items(id) on delete cascade,
  tag_type text not null default 'OWNER'
    check (tag_type in ('OWNER', 'FOUND', 'DROPBOX', 'LOCATION')),
  status text not null default 'ACTIVE'
    check (status in ('ACTIVE', 'INACTIVE', 'REVOKED')),
  created_at timestamptz not null default now()
);


create table if not exists public.lost_reports (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references public.app_users(id) on delete cascade,
  item_id uuid not null references public.items(id) on delete cascade,
  last_seen_text varchar(160) not null,
  status text not null default 'OPEN'
    check (status in ('OPEN', 'CLOSED', 'CANCELLED')),
  created_at timestamptz not null default now(),
  resolved_at timestamptz
);

create table if not exists public.found_reports (
  id uuid primary key default gen_random_uuid(),
  tag_id uuid references public.tags(id) on delete set null,
  item_id uuid references public.items(id) on delete set null,
  finder_telegram_user_id bigint,
  finder_telegram_chat_id bigint,
  message varchar(500),
  location_id uuid,
  dropbox_id uuid,
  status text not null default 'OPEN'
    check (status in ('OPEN', 'OWNER_NOTIFIED', 'CLOSED', 'INVALID')),
  created_at timestamptz not null default now()
);

create table if not exists public.events (
  id bigint generated by default as identity primary key,
  event_type text not null,
  actor_user_id uuid references public.app_users(id) on delete set null,
  actor_telegram_user_id bigint,
  item_id uuid references public.items(id) on delete set null,
  tag_id uuid references public.tags(id) on delete set null,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists idx_items_owner_id on public.items(owner_id);
create index if not exists idx_items_status on public.items(status);
create index if not exists idx_tags_public_token on public.tags(public_token);
create index if not exists idx_lost_reports_owner_id on public.lost_reports(owner_id);
create index if not exists idx_lost_reports_item_id on public.lost_reports(item_id);
create index if not exists idx_lost_reports_status on public.lost_reports(status);
create index if not exists idx_lost_reports_created_at on public.lost_reports(created_at desc);
create index if not exists idx_found_reports_item_id on public.found_reports(item_id);
create index if not exists idx_found_reports_created_at on public.found_reports(created_at desc);
create index if not exists idx_events_item_id on public.events(item_id);
create index if not exists idx_events_created_at on public.events(created_at desc);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists app_users_set_updated_at on public.app_users;
create trigger app_users_set_updated_at
before update on public.app_users
for each row execute function public.set_updated_at();

drop trigger if exists items_set_updated_at on public.items;
create trigger items_set_updated_at
before update on public.items
for each row execute function public.set_updated_at();

create or replace function public.register_tagged_item(
  p_owner_id uuid,
  p_item_name text,
  p_tag_token text,
  p_category text
)
returns table(item_id uuid, tag_id uuid)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_item_id uuid;
  v_tag_id uuid;
begin
  if length(trim(p_item_name)) < 2 then
    raise exception 'INVALID_ITEM_NAME';
  end if;

  if p_tag_token !~ '^PT-[A-Z0-9]{8}$' then
    raise exception 'INVALID_TAG_TOKEN';
  end if;

  if p_category not in ('keys', 'bag', 'laptop', 'phone', 'camera', 'card', 'other') then
    raise exception 'INVALID_CATEGORY';
  end if;

  insert into public.items(owner_id, name, category)
  values (p_owner_id, trim(p_item_name), p_category)
  returning id into v_item_id;

  insert into public.tags(public_token, item_id)
  values (upper(p_tag_token), v_item_id)
  returning id into v_tag_id;

  return query select v_item_id, v_tag_id;
exception
  when unique_violation then
    raise exception 'TAG_ALREADY_EXISTS';
end;
$$;

